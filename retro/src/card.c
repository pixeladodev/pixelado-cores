static const uint8_t *glyph(char c)
{
    size_t i;
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (i = 0; i < sizeof FONT / sizeof FONT[0]; i++)
        if (FONT[i].c == c) return FONT[i].r;
    return glyph('?');
}

void px_fill(px_canvas *c, int x, int y, int w, int h, uint32_t col)
{
    int i, j;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > c->w) w = c->w - x;
    if (y + h > c->h) h = c->h - y;
    for (j = 0; j < h; j++) {
        uint32_t *r = c->px + (size_t)(y + j) * (size_t)c->pitch + x;
        for (i = 0; i < w; i++) r[i] = col;
    }
}

int px_text_w(int s, const char *t)
{
    size_t n = strlen(t);
    return n ? (int)n * 6 * s - s : 0;
}

int px_text(px_canvas *c, int x, int y, int s, uint32_t col, const char *t)
{
    int x0 = x;
    for (; *t; t++) {
        const uint8_t *g;
        int r, b;
        if ((unsigned char)*t >= 0x80) {   /* (a UTF-8 sequence: one '?' for it) */
            while ((unsigned char)t[1] >= 0x80 && ((unsigned char)t[1] & 0xC0) == 0x80) t++;
            g = glyph('?');
        } else
            g = glyph(*t);
        if (x + 5 * s > c->w) break;
        for (r = 0; r < 7; r++)
            for (b = 0; b < 5; b++)
                if (g[r] & (0x10 >> b)) px_fill(c, x + b * s, y + r * s, s, s, col);
        x += 6 * s;
    }
    return x - x0;
}

void px_card_draw(px_canvas *c, const px_card *k)
{
    const int s = c->w >= 960 ? 4 : c->w >= 600 ? 3 : 2, big = s + 1;
    const int m = c->w / 16;
    int y = c->h / 8, i;
    char fps[24];
    px_fill(c, 0, 0, c->w, c->h, PX_BG);
    /* a frame in the brand's blues */
    px_fill(c, m / 2, m / 2, c->w - m, s, PX_BG2);
    px_fill(c, m / 2, c->h - m / 2 - s, c->w - m, s, PX_BG2);
    px_text(c, m, y, big, PX_INK, k->title[0] ? k->title : "PIXELADO");
    y += 7 * big + 3 * s;
    px_fill(c, m, y, c->w - 2 * m, s / 2 > 0 ? s / 2 : 1, PX_ACCENT);
    y += 6 * s;
    for (i = 0; i < 4; i++) {
        if (!k->line[i][0]) continue;
        px_text(c, m, y, s, k->line_col[i] ? k->line_col[i] : PX_MUTED, k->line[i]);
        y += 7 * s + 4 * s;
    }
    if (k->foot[0]) px_text(c, m, c->h - m - 7 * s, s, PX_MUTED, k->foot);
    if (k->fps >= 0) {
        int n = k->fps;
        fps[0] = 0;
        /* (no printf here: it is a hot path when the counter is on) */
        {
            char d[8];
            int j = 0, o = 0;
            do { d[j++] = (char)('0' + n % 10); n /= 10; } while (n && j < 6);
            while (j) fps[o++] = d[--j];
            memcpy(fps + o, " FPS", 5);
        }
        px_text(c, c->w - m - px_text_w(s, fps), m, s, PX_INK, fps);
    }
}
